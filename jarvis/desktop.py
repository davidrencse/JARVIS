"""Lan Mouse pairing helpers. Only certificate fingerprints leave a device, never the key."""

import base64
import hashlib
import os
import re
import shutil
import subprocess
from pathlib import Path

POSITIONS = ("left", "right", "top", "bottom")
OPPOSITE = {"left": "right", "right": "left", "top": "bottom", "bottom": "top"}

# Runs on the remote host; reads the CERTIFICATE block only and prints its fingerprint.
REMOTE_FINGERPRINT = r"""
import base64, hashlib, os, re, sys
home = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
try:
    text = open(os.path.join(home, "lan-mouse", "lan-mouse.pem"), encoding="ascii").read()
except FileNotFoundError:
    sys.exit("missing: start Lan Mouse once on this device to create its certificate")
m = re.search(r"-----BEGIN CERTIFICATE-----(.+?)-----END CERTIFICATE-----", text, re.S)
if not m:
    sys.exit("no certificate block")
d = hashlib.sha256(base64.b64decode("".join(m.group(1).split()))).hexdigest()
print(":".join(d[i:i + 2] for i in range(0, 64, 2)))
"""


def pem_fingerprint(text):
    """Lan Mouse's fingerprint: SHA-256 of the certificate DER, colon-separated hex."""
    match = re.search(r"-----BEGIN CERTIFICATE-----(.+?)-----END CERTIFICATE-----", text, re.S)
    if not match:
        raise ValueError("No certificate block in the Lan Mouse PEM file.")
    digest = hashlib.sha256(base64.b64decode("".join(match.group(1).split()))).hexdigest()
    return ":".join(digest[i:i + 2] for i in range(0, 64, 2))


def local_cert_path():
    if os.name == "nt":
        base = Path(os.environ.get("LOCALAPPDATA") or Path.home() / ".config")
    else:
        base = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return base / "lan-mouse" / "lan-mouse.pem"


def local_fingerprint():
    path = local_cert_path()
    if not path.is_file():
        raise ValueError(f"No Lan Mouse certificate at {path}; start Lan Mouse once first.")
    return pem_fingerprint(path.read_text(encoding="ascii"))


def remote_fingerprint(target, identity_file=None):
    binary = shutil.which("ssh")
    if not binary:
        raise ValueError("OpenSSH client is not installed.")
    identity_args = []
    if identity_file:
        identity_args = ["-i", str(Path(identity_file).expanduser()), "-o", "IdentitiesOnly=yes"]
    result = subprocess.run(
        [binary, "-T", *identity_args, "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=yes",
         "-o", "ConnectTimeout=8", target, "python3 -"],
        input=REMOTE_FINGERPRINT, capture_output=True, text=True, timeout=30, shell=False)
    if result.returncode:
        raise RuntimeError("Remote fingerprint failed: " + (result.stderr or result.stdout)[-500:])
    value = result.stdout.strip()
    if not re.fullmatch(r"(?:[0-9a-f]{2}:){31}[0-9a-f]{2}", value):
        raise RuntimeError("Remote host returned an unexpected fingerprint format.")
    return value


def lan_mouse_config(peer_name, peer_ips, position, peer_fingerprint,
                     release_bind=("KeyLeftCtrl", "KeyLeftShift", "KeyLeftMeta", "KeyLeftAlt"),
                     port=4242, capture_backend=None):
    """TOML for one side: the peer sits at `position`, and only its certificate is trusted."""
    if position not in POSITIONS:
        raise ValueError(f"position must be one of {', '.join(POSITIONS)}.")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.-]*", peer_name):
        raise ValueError("Peer name must be a plain hostname.")
    for ip in peer_ips:
        if (not re.fullmatch(r"\d{1,3}(?:\.\d{1,3}){3}", ip)
                or any(int(octet) > 255 for octet in ip.split("."))):
            raise ValueError(f"Not an IPv4 address: {ip}")
    if not re.fullmatch(r"(?:[0-9a-f]{2}:){31}[0-9a-f]{2}", peer_fingerprint):
        raise ValueError("Fingerprint must be 32 colon-separated lowercase hex bytes.")
    if capture_backend not in (None, "input-capture-portal", "layer-shell", "windows"):
        raise ValueError("Unsupported capture backend.")
    binds = ", ".join(f'"{key}"' for key in release_bind)
    ips = ", ".join(f'"{ip}"' for ip in peer_ips)
    backend = f'capture_backend = "{capture_backend}"\n' if capture_backend else ""
    return (
        "# Generated by JARVIS. Peer certificate fingerprint verified out of band.\n"
        f"{backend}"
        f"release_bind = [ {binds} ]\n"
        f"port = {int(port)}\n\n"
        "[authorized_fingerprints]\n"
        f'"{peer_fingerprint}" = "{peer_name}"\n\n'
        "[[clients]]\n"
        f'position = "{position}"\n'
        f'hostname = "{peer_name}"\n'
        "activate_on_startup = true\n"
        f"ips = [ {ips} ]\n"
        f"port = {int(port)}\n"
    )
